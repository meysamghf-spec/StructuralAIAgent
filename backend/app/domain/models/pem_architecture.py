class FloorPlanDefinition(BaseModel):
    """
    One storey of the building. ``boundary`` is the built footprint on that storey,
    which sits inside ``SiteDefinition.buildable_boundary``.
    """

    id: str = Field(default_factory=lambda: new_architectural_id("FLR"))
    name: str
    level_id: str
    floor_type: FloorType
    elevation_m: float
    storey_height_m: float
    boundary: Polygon2D
    spaces: list[SpaceDefinition] = Field(default_factory=list)
    walls: list[WallDefinition] = Field(default_factory=list)
    doors: list[DoorDefinition] = Field(default_factory=list)
    windows: list[WindowDefinition] = Field(default_factory=list)
    parking_spaces: list[ParkingSpaceDefinition] = Field(default_factory=list)
    apartments: list[ApartmentDefinition] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def gross_area_m2(self) -> float:
        return round(self.boundary.area, 4)

    def spaces_with_usage(self, *usages: SpaceUsage) -> list[SpaceDefinition]:
        wanted = set(usages)
        return [space for space in self.spaces if space.usage in wanted]

    @property
    def rooms(self) -> list[SpaceDefinition]:
        """Habitable rooms (excludes circulation, shafts and parking)."""
        return self.spaces_with_usage(
            SpaceUsage.BEDROOM,
            SpaceUsage.MASTER_BEDROOM,
            SpaceUsage.LIVING,
            SpaceUsage.KITCHEN,
            SpaceUsage.BATHROOM,
            SpaceUsage.WC,
            SpaceUsage.STORAGE,
        )

    @property
    def corridors(self) -> list[SpaceDefinition]:
        return self.spaces_with_usage(SpaceUsage.CORRIDOR, SpaceUsage.LOBBY, SpaceUsage.ENTRANCE)

    @property
    def shafts(self) -> list[SpaceDefinition]:
        return self.spaces_with_usage(SpaceUsage.SHAFT)


class StructuralSystem(StrEnum):
    RC_MOMENT_FRAME = "RC_MOMENT_FRAME"
    RC_FRAME_WITH_SHEAR_WALLS = "RC_FRAME_WITH_SHEAR_WALLS"
    STEEL_MOMENT_FRAME = "STEEL_MOMENT_FRAME"
    UNDETERMINED = "UNDETERMINED"


class BuildingModel(BaseModel):
    """
    The architectural half of the PEM, in the same coordinate frame as
    ``StructuralModel``. Empty by default so existing PEM snapshots stay valid.
    """

    length_unit: str = "m"
    site: SiteDefinition | None = None
    floor_plans: list[FloorPlanDefinition] = Field(default_factory=list)
    stairs: list[StairDefinition] = Field(default_factory=list)
    elevators: list[ElevatorDefinition] = Field(default_factory=list)
    cores: list[CoreDefinition] = Field(default_factory=list)
    structural_system: StructuralSystem = StructuralSystem.UNDETERMINED
    generated_by: str | None = None
    generation_assumptions: list[str] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def floor_count(self) -> int:
        return len(self.floor_plans)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def total_built_area_m2(self) -> float:
        return round(sum(plan.boundary.area for plan in self.floor_plans), 4)

    @property
    def is_populated(self) -> bool:
        return self.site is not None and bool(self.floor_plans)

    def floor_plan_for_level(self, level_id: str) -> FloorPlanDefinition | None:
        for plan in self.floor_plans:
            if plan.level_id == level_id:
                return plan
        return None

    def all_spaces(self) -> list[SpaceDefinition]:
        return [space for plan in self.floor_plans for space in plan.spaces]

    def all_parking_spaces(self) -> list[ParkingSpaceDefinition]:
        return [slot for plan in self.floor_plans for slot in plan.parking_spaces]


def create_empty_building_model() -> BuildingModel:
    return BuildingModel()
