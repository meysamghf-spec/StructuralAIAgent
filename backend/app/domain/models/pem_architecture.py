class SiteDefinition(BaseModel):
    """Plot geometry, frontage and setbacks. All distances in metres."""

    id: str = Field(default_factory=lambda: new_architectural_id("SITE"))
    name: str = "Plot"
    boundary: Polygon2D = Field(default_factory=Polygon2D)
    frontage_m: float = 0.0
    depth_m: float = 0.0
    orientation_deg: float = 0.0
    setback_front_m: float = 0.0
    setback_rear_m: float = 0.0
    setback_left_m: float = 0.0
    setback_right_m: float = 0.0
    metadata: dict[str, Any] = Field(default_factory=dict)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def plot_area_m2(self) -> float:
        return round(self.boundary.area, 4)

    @property
    def buildable_boundary(self) -> Polygon2D:
        """Plot boundary reduced by the four setbacks."""
        min_x, min_y, max_x, max_y = self.boundary.bounds
        x0 = min_x + self.setback_left_m
        y0 = min_y + self.setback_front_m
        width = (max_x - self.setback_right_m) - x0
        depth = (max_y - self.setback_rear_m) - y0
        if width <= 0.0 or depth <= 0.0:
            return Polygon2D()
        return rectangle(x0, y0, width, depth)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def buildable_area_m2(self) -> float:
        return round(self.buildable_boundary.area, 4)


