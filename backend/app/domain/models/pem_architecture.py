class SpaceDefinition(BaseModel):
    """
    A single enclosed architectural space with real geometry.

    Rooms, corridors, lobbies and shafts are all this type; ``usage`` carries the
    distinction so there is only one spatial record per physical space.
    """

    id: str = Field(default_factory=lambda: new_architectural_id("SPC"))
    name: str
    usage: SpaceUsage
    boundary: Polygon2D
    level_id: str
    apartment_id: str | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def area_m2(self) -> float:
        return round(self.boundary.area, 4)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def width_m(self) -> float:
        return round(self.boundary.width, 4)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def depth_m(self) -> float:
        return round(self.boundary.depth, 4)


