"""
Architectural / site geometry entities for ProjectEngineeringModel.

Coordinate system (shared with ``pem_structural``):

* Units are **metres**. ``BuildingModel.length_unit`` records this explicitly so a
  consumer never has to guess.
* Origin ``(0, 0)`` is the front-left corner of the plot.
* ``+x`` runs along the frontage, ``+y`` runs into the depth of the plot, ``+z`` is up.

Architecture and structure deliberately share this frame so a column generated by
``StructuralLayoutGenerator`` can be tested against a room generated by
``BuildingLayoutGenerator`` without any transform.

``Room``, ``Corridor`` and ``Shaft`` are all represented by :class:`SpaceDefinition`
and distinguished by :class:`SpaceUsage`. There is intentionally no second geometry
store for them.
"""

from __future__ import annotations

import math
from enum import StrEnum
from typing import Any
from uuid import uuid4

from pydantic import BaseModel, Field, computed_field, model_validator


def new_architectural_id(prefix: str) -> str:
    return f"{prefix}-{uuid4().hex[:12]}"


# ---------------------------------------------------------------------------
# Geometry primitives
# ---------------------------------------------------------------------------


class Point2D(BaseModel):
    x: float
    y: float

    def distance_to(self, other: Point2D) -> float:
        return math.hypot(self.x - other.x, self.y - other.y)

    def as_tuple(self) -> tuple[float, float]:
        return (self.x, self.y)


class Polygon2D(BaseModel):
    """Simple closed polygon. The closing edge is implicit (last point -> first)."""

    points: list[Point2D] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_ring(self) -> Polygon2D:
        if self.points and len(self.points) < 3:
            raise ValueError("A polygon boundary requires at least three points")
        return self

    @computed_field  # type: ignore[prop-decorator]
    @property
    def area(self) -> float:
        """Shoelace area. Always non-negative so winding order never leaks out."""
        if len(self.points) < 3:
            return 0.0
        total = 0.0
        count = len(self.points)
        for index in range(count):
            current = self.points[index]
            following = self.points[(index + 1) % count]
            total += current.x * following.y - following.x * current.y
        return abs(total) / 2.0

    @computed_field  # type: ignore[prop-decorator]
    @property
    def perimeter(self) -> float:
        if len(self.points) < 2:
            return 0.0
        count = len(self.points)
        return sum(self.points[i].distance_to(self.points[(i + 1) % count]) for i in range(count))

    @property
    def centroid(self) -> Point2D:
        if not self.points:
            return Point2D(x=0.0, y=0.0)
        if len(self.points) < 3:
            return Point2D(
                x=sum(p.x for p in self.points) / len(self.points),
                y=sum(p.y for p in self.points) / len(self.points),
            )
        area_signed = 0.0
        cx = 0.0
        cy = 0.0
        count = len(self.points)
        for index in range(count):
            current = self.points[index]
            following = self.points[(index + 1) % count]
            cross = current.x * following.y - following.x * current.y
            area_signed += cross
            cx += (current.x + following.x) * cross
            cy += (current.y + following.y) * cross
        if abs(area_signed) < 1e-12:
            return Point2D(
                x=sum(p.x for p in self.points) / count,
                y=sum(p.y for p in self.points) / count,
            )
        factor = 1.0 / (3.0 * area_signed)
        return Point2D(x=cx * factor, y=cy * factor)

    @property
    def bounds(self) -> tuple[float, float, float, float]:
        """``(min_x, min_y, max_x, max_y)``."""
        if not self.points:
            return (0.0, 0.0, 0.0, 0.0)
        xs = [point.x for point in self.points]
        ys = [point.y for point in self.points]
        return (min(xs), min(ys), max(xs), max(ys))

    @property
    def width(self) -> float:
        min_x, _, max_x, _ = self.bounds
        return max_x - min_x

    @property
    def depth(self) -> float:
        _, min_y, _, max_y = self.bounds
        return max_y - min_y

    def contains_point(self, point: Point2D, *, tolerance: float = 1e-9) -> bool:
        """Ray-casting point-in-polygon. Boundary points count as inside."""
        if len(self.points) < 3:
            return False
        count = len(self.points)
        for index in range(count):
            if _point_on_segment(point, self.points[index], self.points[(index + 1) % count], tolerance):
                return True
        inside = False
        for index in range(count):
            current = self.points[index]
            following = self.points[(index + 1) % count]
            if (current.y > point.y) != (following.y > point.y):
                denominator = following.y - current.y
                if abs(denominator) < tolerance:
                    continue
                x_cross = current.x + (point.y - current.y) * (following.x - current.x) / denominator
                if point.x < x_cross:
                    inside = not inside
        return inside

    def overlap_area_with(self, other: Polygon2D) -> float:
        """
        Axis-aligned overlap area.

        Every polygon produced by the layout generators is a rectangle, so a
        bounding-box intersection is exact for them. For non-rectangular polygons
        this is a conservative upper bound, which is the safe direction for an
        overlap *check*.
        """
        a_min_x, a_min_y, a_max_x, a_max_y = self.bounds
        b_min_x, b_min_y, b_max_x, b_max_y = other.bounds
        overlap_x = min(a_max_x, b_max_x) - max(a_min_x, b_min_x)
        overlap_y = min(a_max_y, b_max_y) - max(a_min_y, b_min_y)
        if overlap_x <= 0.0 or overlap_y <= 0.0:
            return 0.0
        return overlap_x * overlap_y

    def contains_polygon(self, other: Polygon2D, *, tolerance: float = 1e-6) -> bool:
        a_min_x, a_min_y, a_max_x, a_max_y = self.bounds
        b_min_x, b_min_y, b_max_x, b_max_y = other.bounds
        return (
            b_min_x >= a_min_x - tolerance
            and b_min_y >= a_min_y - tolerance
            and b_max_x <= a_max_x + tolerance
            and b_max_y <= a_max_y + tolerance
        )


def _point_on_segment(point: Point2D, start: Point2D, end: Point2D, tolerance: float) -> bool:
    cross = (end.x - start.x) * (point.y - start.y) - (end.y - start.y) * (point.x - start.x)
    if abs(cross) > tolerance * max(1.0, start.distance_to(end)):
        return False
    dot = (point.x - start.x) * (end.x - start.x) + (point.y - start.y) * (end.y - start.y)
    if dot < -tolerance:
        return False
    length_squared = (end.x - start.x) ** 2 + (end.y - start.y) ** 2
    return dot <= length_squared + tolerance


def rectangle(origin_x: float, origin_y: float, width: float, depth: float) -> Polygon2D:
    """Counter-clockwise axis-aligned rectangle."""
    return Polygon2D(
        points=[
            Point2D(x=origin_x, y=origin_y),
            Point2D(x=origin_x + width, y=origin_y),
            Point2D(x=origin_x + width, y=origin_y + depth),
            Point2D(x=origin_x, y=origin_y + depth),
        ]
    )


