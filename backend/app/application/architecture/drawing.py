M = 1000.0  # m -> mm
for k, v in ARCH_LAYERS.items():
    ds.LAYERS.setdefault(k, v)


def new_doc():
    doc = ds.new_document()
    for name, (color, lw, lt) in ARCH_LAYERS.items():
        if name not in doc.layers:
            doc.layers.add(name, color=color, lineweight=lw, linetype=lt)
    return doc


@dataclass
class Sheet:
    no: str
    title_en: str
    title_fa: str
    doc: Any
    scale: int
    kind: str


class AP(Pen):
    """Pen working in metres (converted to mm)."""

    def P(self, x, y):
        return (x * M, y * M)

    def mline(self, layer, a, b):
        return self.line(layer, self.P(*a), self.P(*b))

    def mpoly(self, layer, pts, closed=False):
        return self.poly(layer, [self.P(*q) for q in pts], closed)

    def mrect(self, layer, x0, y0, x1, y1):
        return self.rect(layer, x0 * M, y0 * M, x1 * M, y1 * M)

    def mfill(self, layer, pts):
        return self.hatch(layer, [self.P(*q) for q in pts], solid=True)

    def mpat(self, layer, pts, pattern="ANSI31", sc=None):
        return self.hatch(layer, [self.P(*q) for q in pts], pattern=pattern, pscale=sc)

    def mtext(self, layer, pos, s, h=2.5, align="MIDDLE_CENTER", rot=0.0):
        return self.text(layer, self.P(*pos), s, h=h, align=align, rot=rot)

    def marc(self, layer, c, r, a0, a1):
        return self.msp.add_arc(self.p(c[0] * M, c[1] * M), r * M, a0, a1, dxfattribs={"layer": layer})

    def mcircle(self, layer, c, r):
        return self.circle(layer, self.P(*c), r * M)


# ---------------------------------------------------------------- frame / title block in model space
def frame(pen: AP, ext_m, sheet_no: str, title_en: str, title_fa: str, info: ds.TitleInfo, scale: int) -> tuple:
    x0, y0, x1, y1 = ext_m
    s = scale / 1000.0  # paper mm -> m
    pad = 15 * s
    tb_h = 32 * s
    bx0, by0, bx1, by1 = x0 - pad, y0 - pad - tb_h, x1 + pad, y1 + pad
    tw = max(150 * s, (bx1 - bx0) * 0.5)
    tw = min(tw, bx1 - bx0)
    pen.mrect("S-BORDER", bx0, by0, bx1, by1)
    tx = bx1 - tw
    pen.mrect("S-TITLEBLOCK", tx, by0, bx1, by0 + tb_h)
    rows = [("Project / پروژه", info.project), ("Drawing / عنوان", title_en), ("", title_fa),
            ("Designer / طراح", info.designer)]
    rh = tb_h / (len(rows) + 1)
    for i, (k, v) in enumerate(rows):
        yy = by0 + tb_h - (i + 1) * rh
        pen.mline("S-TITLEBLOCK", (tx, yy), (bx1, yy))
        pen.mtext("S-TITLEBLOCK", (tx + 2 * s, yy + rh / 2), k, h=1.8, align="MIDDLE_LEFT")
        pen.mtext("S-TITLEBLOCK", (tx + tw * 0.35, yy + rh / 2), v, h=2.4, align="MIDDLE_LEFT")
    cells = [("Sheet", sheet_no), ("Scale / مقیاس", f"1:{scale}"), ("Date / تاریخ", info.drawing_date), ("Code", "Mabhas 4")]
    cw = tw / len(cells)
    for i, (k, v) in enumerate(cells):
        cx = tx + i * cw
        pen.mline("S-TITLEBLOCK", (cx, by0), (cx, by0 + rh))
        pen.mtext("S-TITLEBLOCK", (cx + 1.5 * s, by0 + rh * 0.75), k, h=1.3, align="MIDDLE_LEFT")
        pen.mtext("S-TITLEBLOCK", (cx + 1.5 * s, by0 + rh * 0.3), v, h=2.0, align="MIDDLE_LEFT")
    pen.mtext("S-TITLE", (bx0 + 4 * s, by0 + tb_h * 0.65), f"{sheet_no}  {title_en}", h=3.5, align="MIDDLE_LEFT")
    pen.mtext("S-TITLE", (bx0 + 4 * s, by0 + tb_h * 0.3), title_fa, h=3.0, align="MIDDLE_LEFT")
    pen.mtext("S-NOTES", (bx0 + 4 * s, by0 + 3 * s), "Generated by SAAI - check before construction / قبل از اجرا کنترل شود", h=1.6, align="MIDDLE_LEFT")
    return (bx0, by0, bx1, by1)


def _finish(doc, pen: AP, ext_m, no, title_en, title_fa, info, scale, kind) -> Sheet:
    b = frame(pen, ext_m, no, title_en, title_fa, info, scale)
    ext = (b[0] * M, b[1] * M, b[2] * M, b[3] * M)
    try:
        ds.add_sheet(doc, no, ext, info, no, title_fa, title_en, scale=scale)
    except Exception:  # noqa: BLE001 - paper space is a bonus; model space is complete
        pass
    return Sheet(no, title_en, title_fa, doc, scale, kind)


def _scale_for(w_m: float, h_m: float) -> int:
    return 50 if max(w_m, h_m) <= 9 else (100 if max(w_m, h_m) <= 30 else 200)


# ---------------------------------------------------------------- plan elements
def _wall_t(L: Layout, horizontal: bool, line: float, kinds: set[str]) -> float:
    r = L.rules
    if horizontal and (abs(line) < 1e-6 or abs(line - L.D) < 1e-6):
        return r.exterior_wall_m
    if not horizontal and (abs(line) < 1e-6 or abs(line - L.W) < 1e-6):
        return r.party_wall_m
    if kinds & {"stair", "elevator", "stairhouse"}:
        return 0.20
    return r.interior_wall_m


def wall_segments(L: Layout, fl: Floor):
    """Axis-aligned wall pieces [(horizontal, line, a0, a1, t)] from room edges (open pairs skipped)."""
    from .layout import OPEN_PAIRS
    rooms = fl.rooms
    out = []
    for horizontal in (True, False):
        lines = sorted({round(v, 4) for rm in rooms for v in ((rm.y0, rm.y1) if horizontal else (rm.x0, rm.x1))})
        for ln in lines:
            edges = []
            for rm in rooms:
                lo, hi = (rm.x0, rm.x1) if horizontal else (rm.y0, rm.y1)
                e0, e1 = (rm.y0, rm.y1) if horizontal else (rm.x0, rm.x1)
                if abs(e0 - ln) < 1e-4:
                    edges.append((lo, hi, rm, "above"))
                if abs(e1 - ln) < 1e-4:
                    edges.append((lo, hi, rm, "below"))
            brk = sorted({round(v, 4) for lo, hi, _, _ in edges for v in (lo, hi)})
            cur = None
            for a, b in zip(brk, brk[1:]):
                m = (a + b) / 2
                side = {"above": None, "below": None}
                for lo, hi, rm, sd in edges:
                    if lo - 1e-6 <= m <= hi + 1e-6:
                        side[sd] = rm
                ra, rb = side["above"], side["below"]
                if ra is None and rb is None:
                    piece = None
                elif ra is not None and rb is not None and (frozenset((ra.kind, rb.kind)) in OPEN_PAIRS and ra.unit == rb.unit):
                    piece = None
                else:
                    kinds = {x.kind for x in (ra, rb) if x is not None}
                    piece = _wall_t(L, horizontal, ln, kinds)
                    if fl.kind == "roof" and kinds <= {"roof"}:
                        piece = None
                if piece is not None and cur and abs(cur[3] - a) < 1e-6 and cur[4] == piece:
                    cur[3] = b
                else:
                    if cur:
                        out.append(tuple(cur))
                    cur = [horizontal, ln, a, b, piece] if piece is not None else None
            if cur:
                out.append(tuple(cur))
    return out


def _wall_rect(L, horizontal, ln, a, b, t):
    """Exterior/party walls grow inward, interior walls are centred."""
    if horizontal:
        if abs(ln) < 1e-6:
            y0, y1 = 0, t
        elif abs(ln - L.D) < 1e-6:
            y0, y1 = L.D - t, L.D
        else:
            y0, y1 = ln - t / 2, ln + t / 2
        return [(a, y0), (b, y0), (b, y1), (a, y1)]
    if abs(ln) < 1e-6:
        x0, x1 = 0, t
    elif abs(ln - L.W) < 1e-6:
        x0, x1 = L.W - t, L.W
    else:
        x0, x1 = ln - t / 2, ln + t / 2
    return [(x0, a), (x1, a), (x1, b), (x0, b)]


def draw_walls(pen: AP, L: Layout, fl: Floor):
    for horizontal, ln, a, b, t in wall_segments(L, fl):
        ops = sorted([(o.a0, o.a1) for o in fl.openings if o.horizontal == horizontal and abs(o.line - ln) < 1e-4 and o.a1 > a and o.a0 < b])
        cur = a
        pieces = []
        for o0, o1 in ops:
            if o0 > cur:
                pieces.append((cur, o0))
            cur = max(cur, o1)
        if cur < b:
            pieces.append((cur, b))
        for p0, p1 in pieces:
            if p1 - p0 < 0.01:
                continue
            q = _wall_rect(L, horizontal, ln, p0, p1, t)
            pen.mfill("A-WALL", q)
            pen.mpoly("A-WALL", q, closed=True)


def _wall_faces(L, o: Opening):
    t = L.rules.exterior_wall_m if (o.horizontal and (abs(o.line) < 1e-6 or abs(o.line - L.D) < 1e-6)) else L.rules.interior_wall_m
    q = _wall_rect(L, o.horizontal, o.line, o.a0, o.a1, t)
    if o.horizontal:
        return q[0][1], q[2][1]
    return q[0][0], q[1][0]


def draw_openings(pen: AP, L: Layout, fl: Floor):
    for o in fl.openings:
        f0, f1 = _wall_faces(L, o)
        w = o.a1 - o.a0
        H = o.horizontal
        P = (lambda a, c: (a, c)) if H else (lambda a, c: (c, a))
        if o.kind in ("window", "slider"):
            for c in (f0, (f0 + f1) / 2 - 0.02, (f0 + f1) / 2 + 0.02, f1):
                pen.mline("A-GLAZ", P(o.a0, c), P(o.a1, c))
            pen.mline("A-GLAZ", P(o.a0, f0), P(o.a0, f1)); pen.mline("A-GLAZ", P(o.a1, f0), P(o.a1, f1))
        elif o.kind == "gate":
            for c in (f0, f1):
                pen.mline("A-DOOR", P(o.a0, c), P(o.a1, c))
            pen.mline("A-HIDDEN", P(o.a0, (f0 + f1) / 2), P(o.a1, (f0 + f1) / 2))
        elif o.kind == "door":
            face = f1 if o.swing_pos else f0
            sgn = 1 if o.swing_pos else -1
            hinge = o.a0 if o.hinge_low else o.a1
            free = o.a1 if o.hinge_low else o.a0
            tip = P(hinge, face + sgn * w)
            pen.mline("A-DOOR", P(hinge, face), tip)
            hx, hy = P(hinge, face)
            fx, fy = P(free, face)
            a_free = math.degrees(math.atan2(fy - hy, fx - hx))
            a_tip = math.degrees(math.atan2(tip[1] - hy, tip[0] - hx))
            a0, a1 = sorted((a_free, a_tip))
            if a1 - a0 > 180:
                a0, a1 = a1, a0 + 360
            pen.marc("A-DOOR", (hx, hy), w, a0, a1)
            pen.mline("A-DOOR", P(o.a0, f0), P(o.a0, f1)); pen.mline("A-DOOR", P(o.a1, f0), P(o.a1, f1))
        if o.tag:
            off = 0.55 if (H and o.line > 0.01) or (not H) else -0.55
            if o.kind in ("window", "slider", "gate") and H:
                off = -0.6 if o.line < 0.01 else 0.6
            cx = (o.a0 + o.a1) / 2
            pen.mtext("A-AREA-IDEN", P(cx, (f0 + f1) / 2 + off), o.tag, h=1.8)


def furniture(pen: AP, rm: Room):
    L = "A-FURN"
    x0, y0, x1, y1 = rm.x0 + 0.15, rm.y0 + 0.15, rm.x1 - 0.15, rm.y1 - 0.15
    w, h = x1 - x0, y1 - y0
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    k = rm.kind
    if k in ("bedroom", "master"):
        bw = 1.6 if k == "master" and w >= 3.0 else 0.95
        bl = 2.0
        vert = h >= w
        if vert:  # headboard on the back wall
            bx0, by1 = cx - bw / 2, y1 - (0.05 if rm.y1 > rm.y0 else 0)
            pen.mrect(L, bx0, by1 - bl, bx0 + bw, by1)
            pen.mrect(L, bx0 + 0.08, by1 - 0.45, bx0 + bw - 0.08, by1 - 0.08)
            for sx in (bx0 - 0.5, bx0 + bw + 0.05):
                if x0 <= sx and sx + 0.45 <= x1:
                    pen.mrect(L, sx, by1 - 0.45, sx + 0.45, by1)
            if h - bl > 1.4:  # wardrobe on the opposite wall
                pen.mrect(L, x0, y0, min(x1, x0 + 1.8), y0 + 0.6)
                pen.mline(L, (x0, y0 + 0.3), (min(x1, x0 + 1.8), y0 + 0.3))
        else:
            bx0, by0 = x1 - bl, cy - bw / 2
            pen.mrect(L, bx0, by0, x1, by0 + bw)
            pen.mrect(L, x1 - 0.45, by0 + 0.08, x1 - 0.08, by0 + bw - 0.08)
            if w - bl > 1.2:
                pen.mrect(L, x0, y0, x0 + 0.6, min(y1, y0 + 1.8))
    elif k == "living":
        sw, sd = min(2.6, w * 0.45), 0.85
        sx0 = cx - sw / 2
        pen.mrect(L, sx0, y0 + 0.2, sx0 + sw, y0 + 0.2 + sd)
        pen.mrect(L, sx0, y0 + 0.2, sx0 + sw, y0 + 0.4)
        if h > 3.2:
            pen.mrect(L, sx0 - sd, y0 + 0.2, sx0, y0 + 0.2 + min(2.0, h - 1.2))
            pen.mrect(L, cx - 0.6, y0 + 1.5, cx + 0.6, y0 + 2.1)
        if h > 5.0 and w > 3.5:  # dining set at the back of a deep living room
            tx, ty = cx, y1 - 1.4
            pen.mrect(L, tx - 0.9, ty - 0.45, tx + 0.9, ty + 0.45)
            for dx in (-0.5, 0.5):
                for dy in (-0.75, 0.75):
                    pen.mrect(L, tx + dx - 0.2, ty + dy - 0.2, tx + dx + 0.2, ty + dy + 0.2)
        if w > 4:
            pen.mrect(L, x1 - 0.45, cy - 0.9, x1, cy + 0.9)  # TV unit
    elif k == "family":
        if w > 3.0 and h > 2.4:  # L-sofa, coffee table and TV wall
            pen.mpoly(L, [(x0 + 0.3, y0 + 0.3), (x0 + 2.6, y0 + 0.3), (x0 + 2.6, y0 + 1.1), (x0 + 1.1, y0 + 1.1),
                          (x0 + 1.1, y0 + 2.2), (x0 + 0.3, y0 + 2.2)], closed=True)
            pen.mrect(L, x0 + 1.5, y0 + 1.4, x0 + 2.4, y0 + 2.0)
            pen.mrect(L, x1 - 0.45, cy - 0.8, x1, cy + 0.8)
    elif k == "hall":
        if w > 2.2 and h > 2.2:
            pen.mcircle(L, (cx, cy), 0.55)
            for a in range(0, 360, 90):
                pen.mcircle(L, (cx + 0.8 * math.cos(math.radians(a)), cy + 0.8 * math.sin(math.radians(a))), 0.2)
    elif k == "kitchen":
        F = "A-FIXT"
        pen.mpoly(F, [(x0, y1), (x1, y1), (x1, y1 - 0.6), (x0 + 0.6, y1 - 0.6), (x0 + 0.6, y0 + 0.3), (x0, y0 + 0.3)], closed=True)
        pen.mrect(F, cx - 0.4, y1 - 0.55, cx + 0.4, y1 - 0.1)   # sink
        pen.mcircle(F, (cx + 0.15, y1 - 0.32), 0.05)
        for dx in (0.25, 0.55):                                   # hob
            for dy in (0.2, 0.42):
                pen.mcircle(F, (x0 + dx, y0 + 0.9 + dy), 0.09)
        pen.mrect(F, x1 - 0.75, y1 - 1.45, x1 - 0.05, y1 - 0.7)   # fridge
        pen.mtext(F, (x1 - 0.4, y1 - 1.07), "REF", h=1.2)
    elif k == "bath":
        F = "A-FIXT"
        if h >= 1.7 and w >= 0.75:
            pen.mrect(F, x1 - 0.75, y1 - 1.7, x1, y1)
            pen.mpoly(F, [(x1 - 0.68, y1 - 1.6), (x1 - 0.07, y1 - 1.6), (x1 - 0.07, y1 - 0.1), (x1 - 0.68, y1 - 0.1)], closed=True)
            pen.mcircle(F, (x1 - 0.37, y1 - 0.3), 0.05)
        else:
            pen.mrect(F, x1 - 0.9, y1 - 0.9, x1, y1)
            pen.mline(F, (x1 - 0.9, y1 - 0.9), (x1, y1)); pen.mline(F, (x1 - 0.9, y1), (x1, y1 - 0.9))
        pen.mrect(F, x0, y0 + 0.2, x0 + 0.45, y0 + 0.75)
        pen.mcircle(F, (x0 + 0.22, y0 + 0.47), 0.15)
    elif k == "wc":
        F = "A-FIXT"
        pen.mrect(F, cx - 0.22, y1 - 0.2, cx + 0.22, y1)
        pen.mpoly(F, [(cx - 0.2, y1 - 0.2), (cx - 0.18, y1 - 0.62), (cx, y1 - 0.72), (cx + 0.18, y1 - 0.62), (cx + 0.2, y1 - 0.2)], closed=True)
        if w > 1.0:
            pen.mrect(F, x0, y0 + 0.05, x0 + 0.4, y0 + 0.45)
    elif k == "stair" or k == "stairhouse":
        pass


def draw_stair(pen: AP, L: Layout, fl: Floor, x0, y0, x1, y1):
    r = L.rules
    sw = r.stair_width_m
    f = L.stair_flight_len
    yl = y0 + 1.2
    n = L.risers_per_flight - 1
    for col, up in ((x0, True), (x0 + sw + 0.15, False)):
        for i in range(n + 1):
            yy = yl + i * r.tread_m
            pen.mline("A-FLOR-STRS", (col, yy), (col + sw, yy))
    pen.mrect("A-FLOR-STRS", x0 + sw, yl, x0 + sw + 0.15, yl + f)
    if fl.kind != "roof":
        pen.mline("A-FLOR-STRS", (x0 + sw / 2, yl + 0.1), (x0 + sw / 2, yl + f + 0.6))
        pen.mpoly("A-FLOR-STRS", [(x0 + sw / 2 - 0.12, yl + f + 0.4), (x0 + sw / 2, yl + f + 0.6), (x0 + sw / 2 + 0.12, yl + f + 0.4)])
        pen.mtext("A-FLOR-STRS", (x0 + sw / 2, yl - 0.35), "UP / بالا", h=1.6)
        cut = yl + f * 0.55
        pen.mline("A-FLOR-STRS", (x0, cut - 0.15), (x0 + sw, cut + 0.15))


def draw_elevator(pen: AP, sh):
    x0, y0, x1, y1 = sh
    pen.mline("A-FIXT", (x0 + 0.15, y0 + 0.15), (x1 - 0.15, y1 - 0.15))
    pen.mline("A-FIXT", (x0 + 0.15, y1 - 0.15), (x1 - 0.15, y0 + 0.15))
    pen.mrect("A-FIXT", x0 + 0.2, y0 + 0.2, x1 - 0.2, y1 - 0.2)


def room_label(pen: AP, rm: Room, show_area=True):
    cx, cy = (rm.x0 + rm.x1) / 2, (rm.y0 + rm.y1) / 2
    w = rm.x1 - rm.x0
    h = 2.2 if w > 2.4 else 1.6
    dy = 0.0 if rm.kind not in ("bedroom", "master", "living", "kitchen", "bath", "wc") else -0.0
    if rm.kind in ("bedroom", "master"):
        cy = rm.y0 + (rm.y1 - rm.y0) * 0.35
    if rm.kind == "kitchen":
        cy = rm.y0 + (rm.y1 - rm.y0) * 0.4; cx = rm.x0 + w * 0.6
    if rm.kind == "living":
        cy = rm.y0 + (rm.y1 - rm.y0) * 0.55
    pen.mtext("A-AREA-IDEN", (cx, cy + 0.35 + dy), rm.fa, h=h + 0.3)
    pen.mtext("A-AREA-IDEN", (cx, cy + dy), rm.en.upper(), h=h * 0.8)
    if show_area and rm.kind not in ("elevator",):
        pen.mtext("A-AREA-IDEN", (cx, cy - 0.32 + dy), f"{rm.area:.1f} m²", h=h * 0.75)


def plan_sheet(L: Layout, fl: Floor, no: str, info: ds.TitleInfo) -> Sheet:
    doc = new_doc()
    msp = doc.modelspace()
    scale = _scale_for(L.W, L.D) if L.W > 9 else 50
    scale = 100 if scale < 100 and L.D > 12 else scale
    pen = AP(msp, scale=scale)
    W, D = L.W, L.D
    if fl.kind == "roof":
        t = L.rules.exterior_wall_m
        pen.mfill("A-WALL", [(0, 0), (W, 0), (W, 0.2), (0, 0.2)])
        for q in ([(0, D - 0.2), (W, D - 0.2), (W, D), (0, D)], [(0, 0), (0.2, 0), (0.2, D), (0, D)], [(W - 0.2, 0), (W, 0), (W, D), (W - 0.2, D)]):
            pen.mfill("A-WALL", q)
        pen.mtext("A-ROOF", (W / 2, 0.45), f"PARAPET h={L.rules.parapet_m:.2f} m / جان پناه", h=1.8)
        # slope arrows to drains
        for (dx, dy) in ((W * 0.25, D * 0.3), (W * 0.65, D * 0.3)):
            pen.mcircle("A-ROOF", (dx, dy), 0.12)
            pen.mtext("A-ROOF", (dx, dy - 0.35), "RD Ø100", h=1.5)
            for ax, ay in ((dx - 1.6, dy + 1.2), (dx + 1.6, dy + 1.2)):
                pen.mline("A-ROOF", (ax, ay), (dx, dy))
        pen.mtext("A-ROOF", (W * 0.45, D * 0.55), "Slope 2% / شیب ۲٪ - isogam + asphalt / عایق ایزوگام", h=1.8)
    # rooms
    sub = [rm for rm in fl.rooms if not (fl.kind == "roof" and rm.kind == "roof")]
    if fl.kind == "roof":
        fl_r = Floor(fl.index, fl.kind, fl.name_en, fl.name_fa, fl.z, fl.height, sub, fl.openings)
        draw_walls(pen, L, fl_r)
    else:
        draw_walls(pen, L, fl)
    draw_openings(pen, L, fl)
    for rm in fl.rooms:
        if rm.kind in ("stair", "stairhouse"):
            draw_stair(pen, L, fl, rm.x0 + (0.1 if rm.x0 > 0 else 0.25), rm.y0, rm.x1, rm.y1)
        elif rm.kind == "elevator":
            draw_elevator(pen, (rm.x0, rm.y0, rm.x1, rm.y1))
        else:
            furniture(pen, rm)
        if rm.kind != "roof":
            room_label(pen, rm)
    for b in fl.balconies:
        pen.mrect("A-BALC", b.x0, b.y0, b.x1, b.y1)
        pen.mrect("A-BALC", b.x0 + 0.05, b.y0 + 0.05, b.x1 - 0.05, b.y1)
        pen.mtext("A-AREA-IDEN", ((b.x0 + b.x1) / 2, (b.y0 + b.y1) / 2), f"بالکن  BALCONY {b.area:.1f} m²", h=1.6)
    for (sx0, sy0, sx1, sy1) in fl.stalls:
        pen.mrect("A-FLOR-PARK", sx0 + 0.05, sy0, sx1 - 0.05, sy1)
        cx = (sx0 + sx1) / 2
        pen.mpoly("A-FLOR-PARK", [(cx - 0.85, sy0 + 0.6), (cx + 0.85, sy0 + 0.6), (cx + 0.85, sy1 - 0.4), (cx - 0.85, sy1 - 0.4)], closed=True)
        pen.mrect("A-FLOR-PARK", cx - 0.75, sy1 - 1.7, cx + 0.75, sy1 - 1.0)
    if fl.stalls:
        pen.mtext("A-FLOR-PARK", (fl.stalls[0][0] + 1.25, 0.9), "▲ ENTRY / ورود خودرو", h=1.8)
    # columns at grid intersections
    cs = 0.40 if L.program.structure == "concrete" else 0.30
    if fl.kind != "roof":
        for gx in L.grid_x:
            for gy in L.grid_y:
                x = min(max(gx, cs / 2), W - cs / 2); y = min(max(gy, cs / 2), D - cs / 2)
                pen.mfill("S-COLS", [(x - cs / 2, y - cs / 2), (x + cs / 2, y - cs / 2), (x + cs / 2, y + cs / 2), (x - cs / 2, y + cs / 2)])
    # grid + dimensions
    pen.grid([g * M for g in L.grid_x], [g * M for g in L.grid_y], [chr(65 + i) for i in range(len(L.grid_x))],
             [str(i + 1) for i in range(len(L.grid_y))], ext=12 * scale, dims=True)
    # room chain dims along the front & right
    xs = sorted({round(rm.x0, 3) for rm in fl.rooms} | {round(rm.x1, 3) for rm in fl.rooms})
    ys = sorted({round(rm.y0, 3) for rm in fl.rooms} | {round(rm.y1, 3) for rm in fl.rooms})
    off = 26 * scale + (L.rules.balcony_depth_m * M if fl.balconies else 0)
    pen.chain_dims([x * M for x in xs], 0.0, -off, horizontal=True)
    pen.chain_dims([y * M for y in ys], W * M, 30 * scale, horizontal=False)
    # north arrow (street on south -> north up)
    na = (W + 40 * scale / M, D)
    pen.north_arrow((na[0] * M, na[1] * M), r=6)
    if L.program.street_side == "north":
        pen.mtext("S-NOTES", (na[0], na[1] - 1.2), "street on the north: N is down / گذر شمالی", h=1.6)
    lvl = "±0.00" if fl.z == 0 else f"+{fl.z:.2f}"
    pen.mtext("S-LEVEL", (W / 2, D + 0.9), f"{fl.name_fa}  -  {fl.name_en}  (FFL {lvl})", h=3.5)
    area = sum(rm.area for rm in fl.rooms if rm.kind not in ("roof",))
    pen.mtext("S-NOTES", (W / 2, -0.9 - (L.rules.balcony_depth_m if fl.balconies else 0) - 28 * scale / M), f"Gross area / زیربنا: {W * D:.1f} m²   net rooms: {area:.1f} m²", h=2.2)
    pad = 48 * scale / M
    ext = (-pad, -pad - (L.rules.balcony_depth_m if fl.balconies else 0), W + pad + 1.5, D + pad)
    return _finish(doc, pen, ext, no, fl.name_en, fl.name_fa, info, scale, "plan")
