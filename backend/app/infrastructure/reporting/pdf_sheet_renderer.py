"""Minimal PDF 1.4 sheet renderer. No third-party PDF library is required."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path


PAGE_W = 842.0  # A4 landscape points
PAGE_H = 595.0
MARGIN = 36.0
TITLE_H = 70.0


def render_pdf_sheet(
    *,
    title: str,
    project_name: str,
    sheet_number: str,
    scale: str,
    notes: list[str],
    lines: list[tuple[float, float, float, float]],
    labels: list[tuple[float, float, str]],
    model_width: float,
    model_height: float,
) -> bytes:
    """
    ``lines`` and ``labels`` are in model metres. They are fitted into the drawing
    window above the title block.
    """
    content = _page_content(
        title=title,
        project_name=project_name,
        sheet_number=sheet_number,
        scale=scale,
        notes=notes,
        lines=lines,
        labels=labels,
        model_width=model_width,
        model_height=model_height,
    )
    objects = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {PAGE_W:.0f} {PAGE_H:.0f}] "
            "/Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>"
        ),
        f"<< /Length {len(content.encode('latin-1', 'replace'))} >>\nstream\n{content}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    body_parts = []
    offsets = [0]
    cursor = 0
    header = "%PDF-1.4\n"
    cursor = len(header.encode("ascii"))
    for index, obj in enumerate(objects, start=1):
        offsets.append(cursor)
        chunk = f"{index} 0 obj\n{obj}\nendobj\n"
        encoded = chunk.encode("latin-1", "replace")
        body_parts.append(encoded)
        cursor += len(encoded)
    xref_pos = cursor
    xref = [f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n"]
    for offset in offsets[1:]:
        xref.append(f"{offset:010d} 00000 n \n")
    trailer = (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_pos}\n%%EOF\n"
    )
    return header.encode("ascii") + b"".join(body_parts) + "".join(xref).encode("ascii") + trailer.encode("ascii")


def write_pdf_sheet(path: Path, **kwargs) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(render_pdf_sheet(**kwargs))
    return path


def _page_content(
    *,
    title: str,
    project_name: str,
    sheet_number: str,
    scale: str,
    notes: list[str],
    lines: list[tuple[float, float, float, float]],
    labels: list[tuple[float, float, str]],
    model_width: float,
    model_height: float,
) -> str:
    ops: list[str] = []
    # Outer frame
    ops.extend(_rect(MARGIN, MARGIN, PAGE_W - 2 * MARGIN, PAGE_H - 2 * MARGIN))
    ops.extend(_rect(MARGIN, MARGIN, PAGE_W - 2 * MARGIN, TITLE_H))
    ops.append(_text(MARGIN + 8, MARGIN + 48, project_name[:80], 11))
    ops.append(_text(MARGIN + 8, MARGIN + 32, title[:80], 10))
    ops.append(_text(MARGIN + 8, MARGIN + 18, f"Sheet {sheet_number}   Scale {scale}   Rev 0", 9))
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    ops.append(_text(MARGIN + 8, MARGIN + 6, f"{stamp}  Generated by SAAI — engineer review required", 8))
    note_x = PAGE_W - MARGIN - 220
    ops.append(_text(note_x, MARGIN + 48, "Notes", 9))
    for index, note in enumerate(notes[:4]):
        ops.append(_text(note_x, MARGIN + 34 - index * 10, f"- {note[:42]}", 7))

    window_x0 = MARGIN + 10
    window_y0 = MARGIN + TITLE_H + 10
    window_w = PAGE_W - 2 * MARGIN - 20
    window_h = PAGE_H - 2 * MARGIN - TITLE_H - 20
    span_x = max(model_width, 1.0)
    span_y = max(model_height, 1.0)
    scale_fit = min(window_w / span_x, window_h / span_y) * 0.90

    def tx(x: float) -> float:
        return window_x0 + x * scale_fit

    def ty(y: float) -> float:
        return window_y0 + y * scale_fit

    for x1, y1, x2, y2 in lines:
        ops.append(f"{tx(x1):.2f} {ty(y1):.2f} m {tx(x2):.2f} {ty(y2):.2f} l S")
    for x, y, label in labels:
        ops.append(_text(tx(x), ty(y), label[:40], 7))
    return "\n".join(["0.2 w"] + ops)


def _rect(x: float, y: float, w: float, h: float) -> list[str]:
    return [
        f"{x:.2f} {y:.2f} m {x + w:.2f} {y:.2f} l {x + w:.2f} {y + h:.2f} l {x:.2f} {y + h:.2f} l h S"
    ]


def _text(x: float, y: float, text: str, size: float) -> str:
    safe = text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    return f"BT /F1 {size:.1f} Tf {x:.2f} {y:.2f} Td ({safe}) Tj ET"
