"""Architectural and schedule DXF views built from the same PEM coordinates."""

from __future__ import annotations

from datetime import UTC, datetime

from app.domain.models.pem import ProjectEngineeringModel
from app.domain.models.pem_architecture import FloorType, Polygon2D, SpaceUsage
from app.domain.models.pem_structural import MemberType
from app.infrastructure.cad.dxf_renderer import (
    DxfRenderResult,
    _build_result,
    _dimension_entity,
    _line_entity,
    _text_entity,
)


def render_building_drawing_dxf(
    pem: ProjectEngineeringModel,
    *,
    drawing_type: str,
    units: str = "METERS",
) -> DxfRenderResult | None:
    normalized = drawing_type.strip().upper()
    dispatch = {
        "SITE_PLAN": _site_plan,
        "PARKING_PLAN": _parking_plan,
        "ARCHITECTURAL_FLOOR_PLAN": _residential_plan,
        "ROOF_PLAN": _roof_plan,
        "ELEVATION": _elevation,
        "SECTION": _section,
        "GRID_PLAN": _grid_plan,
        "FOUNDATION_LAYOUT": _foundation,
        "COLUMN_SCHEDULE": _column_schedule,
        "BEAM_SCHEDULE": _beam_schedule,
        "SLAB_SCHEDULE": _slab_schedule,
    }
    renderer = dispatch.get(normalized)
    if renderer is None:
        return None
    return renderer(pem, drawing_type=normalized, units=units)


def _polygon_lines(layer: str, polygon: Polygon2D) -> list[str]:
    entities: list[str] = []
    points = polygon.points
    for index in range(len(points)):
        start = points[index]
        end = points[(index + 1) % len(points)]
        entities.extend(_line_entity(layer, start.x, start.y, end.x, end.y))
    return entities


def _title(pem: ProjectEngineeringModel, drawing_type: str) -> list[str]:
    name = pem.metadata.name
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    return [
        *_text_entity("TITLE", 0.5, -2.2, name),
        *_text_entity("TITLE", 0.5, -2.9, drawing_type.replace("_", " ")),
        *_text_entity("TITLE", 0.5, -3.6, f"Scale 1:100  |  {stamp}  |  Preliminary automated drawing"),
        *_text_entity("TITLE", 0.5, -4.3, "Generated by SAAI — engineer review required"),
    ]


def _site_plan(pem: ProjectEngineeringModel, *, drawing_type: str, units: str) -> DxfRenderResult:
    building = pem.building_model
    layers = {"PLOT": 0, "BUILDING": 0, "TEXT": 0, "DIMENSIONS": 0, "TITLE": 0}
    entities: list[str] = []
    if building.site is None:
        return _empty(drawing_type, units, "No site geometry")
    entities.extend(_polygon_lines("PLOT", building.site.boundary))
    layers["PLOT"] += len(building.site.boundary.points)
    footprint = building.site.buildable_boundary
    if footprint.points:
        entities.extend(_polygon_lines("BUILDING", footprint))
        layers["BUILDING"] += len(footprint.points)
    min_x, min_y, max_x, max_y = building.site.boundary.bounds
    entities.extend(_dimension_entity("DIMENSIONS", min_x, min_y - 1.2, max_x, min_y - 1.2, f"{building.site.frontage_m:.2f} m frontage"))
    entities.extend(_dimension_entity("DIMENSIONS", min_x - 1.2, min_y, min_x - 1.2, max_y, f"{building.site.depth_m:.2f} m depth"))
    layers["DIMENSIONS"] += 2
    centroid = building.site.boundary.centroid
    entities.extend(_text_entity("TEXT", centroid.x, centroid.y, f"Plot {building.site.plot_area_m2:.1f} m²"))
    layers["TEXT"] += 1
    entities.extend(_title(pem, drawing_type))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "COMPLETE", "plot_area_m2": building.site.plot_area_m2},
    )


def _plan_for_type(pem: ProjectEngineeringModel, floor_type: FloorType):
    for plan in pem.building_model.floor_plans:
        if plan.floor_type is floor_type:
            return plan
    return None


def _floor_plan(
    pem: ProjectEngineeringModel,
    *,
    drawing_type: str,
    units: str,
    floor_type: FloorType,
    include_parking: bool,
) -> DxfRenderResult:
    plan = _plan_for_type(pem, floor_type)
    layers = {"WALLS": 0, "SPACES": 0, "DOORS": 0, "WINDOWS": 0, "PARKING": 0, "GRID": 0, "TEXT": 0, "TITLE": 0}
    entities: list[str] = []
    if plan is None:
        return _empty(drawing_type, units, f"No {floor_type.value} floor")
    entities.extend(_polygon_lines("WALLS", plan.boundary))
    layers["WALLS"] += len(plan.boundary.points)
    for wall in plan.walls:
        entities.extend(_line_entity("WALLS", wall.start.x, wall.start.y, wall.end.x, wall.end.y))
        layers["WALLS"] += 1
    for space in plan.spaces:
        entities.extend(_polygon_lines("SPACES", space.boundary))
        layers["SPACES"] += len(space.boundary.points)
        centre = space.boundary.centroid
        entities.extend(_text_entity("TEXT", centre.x, centre.y, f"{space.name} {space.area_m2:.1f}m²"))
        layers["TEXT"] += 1
    if include_parking:
        for slot in plan.parking_spaces:
            entities.extend(_polygon_lines("PARKING", slot.boundary))
            layers["PARKING"] += len(slot.boundary.points)
            centre = slot.boundary.centroid
            entities.extend(_text_entity("TEXT", centre.x, centre.y, slot.label))
            layers["TEXT"] += 1
    for door in plan.doors:
        entities.extend(_text_entity("DOORS", door.center.x, door.center.y, "D"))
        layers["DOORS"] += 1
    for window in plan.windows:
        entities.extend(_text_entity("WINDOWS", window.center.x, window.center.y, "W"))
        layers["WINDOWS"] += 1
    grid = pem.structural_model.geometry.grids[0].metadata if pem.structural_model.geometry.grids else {}
    for x_value in grid.get("x_ordinates") or []:
        min_y = plan.boundary.bounds[1]
        max_y = plan.boundary.bounds[3]
        entities.extend(_line_entity("GRID", float(x_value), min_y, float(x_value), max_y))
        layers["GRID"] += 1
    for y_value in grid.get("y_ordinates") or []:
        min_x = plan.boundary.bounds[0]
        max_x = plan.boundary.bounds[2]
        entities.extend(_line_entity("GRID", min_x, float(y_value), max_x, float(y_value)))
        layers["GRID"] += 1
    entities.extend(_title(pem, f"{drawing_type} — {plan.name}"))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={
            "capability_status": "COMPLETE",
            "space_count": len(plan.spaces),
            "parking_count": len(plan.parking_spaces),
            "level_id": plan.level_id,
        },
    )


def _parking_plan(pem, *, drawing_type, units):
    return _floor_plan(pem, drawing_type=drawing_type, units=units, floor_type=FloorType.PILOTI, include_parking=True)


def _residential_plan(pem, *, drawing_type, units):
    return _floor_plan(
        pem, drawing_type=drawing_type, units=units, floor_type=FloorType.RESIDENTIAL, include_parking=False
    )


def _roof_plan(pem, *, drawing_type, units):
    return _floor_plan(pem, drawing_type=drawing_type, units=units, floor_type=FloorType.ROOF, include_parking=False)


def _grid_plan(pem: ProjectEngineeringModel, *, drawing_type: str, units: str) -> DxfRenderResult:
    structural = pem.structural_model
    layers = {"GRID": 0, "TEXT": 0, "TITLE": 0}
    entities: list[str] = []
    grid = structural.geometry.grids[0].metadata if structural.geometry.grids else {}
    x_vals = [float(v) for v in grid.get("x_ordinates") or []]
    y_vals = [float(v) for v in grid.get("y_ordinates") or []]
    x_labels = list(grid.get("x_labels") or [])
    y_labels = list(grid.get("y_labels") or [])
    if not x_vals or not y_vals:
        xs = sorted({round(point.x, 4) for point in structural.geometry.points})
        ys = sorted({round(point.y, 4) for point in structural.geometry.points})
        if len(xs) >= 2 and len(ys) >= 2:
            x_vals, y_vals = xs, ys
            x_labels, y_labels = [str(v) for v in xs], [str(v) for v in ys]
        else:
            return _empty(drawing_type, units, "No structural grid")
    for x_value, label in zip(x_vals, x_labels or x_vals):
        entities.extend(_line_entity("GRID", x_value, y_vals[0], x_value, y_vals[-1]))
        entities.extend(_text_entity("TEXT", x_value, y_vals[0] - 0.8, str(label)))
        layers["GRID"] += 1
        layers["TEXT"] += 1
    for y_value, label in zip(y_vals, y_labels or y_vals):
        entities.extend(_line_entity("GRID", x_vals[0], y_value, x_vals[-1], y_value))
        entities.extend(_text_entity("TEXT", x_vals[0] - 0.8, y_value, str(label)))
        layers["GRID"] += 1
        layers["TEXT"] += 1
    entities.extend(_title(pem, drawing_type))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "COMPLETE", "x_count": len(x_vals), "y_count": len(y_vals)},
    )


def _foundation(pem: ProjectEngineeringModel, *, drawing_type: str, units: str) -> DxfRenderResult:
    """Column positions at the lowest level — a footing concept, not a designed foundation."""
    structural = pem.structural_model
    layers = {"FOOTINGS": 0, "TEXT": 0, "TITLE": 0}
    entities: list[str] = []
    lowest = min(structural.geometry.levels, key=lambda item: item.elevation, default=None)
    columns = [
        member
        for member in structural.members.members
        if member.member_type is MemberType.COLUMN and member.level_id == (lowest.id if lowest else None)
    ]
    points = {point.id: point for point in structural.geometry.points}
    for member in columns:
        point = points.get(member.start_point_id or "")
        if point is None:
            continue
        size = 0.9
        entities.extend(_line_entity("FOOTINGS", point.x - size / 2, point.y - size / 2, point.x + size / 2, point.y - size / 2))
        entities.extend(_line_entity("FOOTINGS", point.x + size / 2, point.y - size / 2, point.x + size / 2, point.y + size / 2))
        entities.extend(_line_entity("FOOTINGS", point.x + size / 2, point.y + size / 2, point.x - size / 2, point.y + size / 2))
        entities.extend(_line_entity("FOOTINGS", point.x - size / 2, point.y + size / 2, point.x - size / 2, point.y - size / 2))
        entities.extend(_text_entity("TEXT", point.x, point.y, member.metadata.get("grid_label", member.name)))
        layers["FOOTINGS"] += 4
        layers["TEXT"] += 1
    entities.extend(_title(pem, drawing_type + " (concept — foundation design NOT_CHECKED)"))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "PARTIAL", "footing_count": len(columns), "missing_data": ["Foundation design is not performed"]},
    )


def _elevation(pem: ProjectEngineeringModel, *, drawing_type: str, units: str) -> DxfRenderResult:
    building = pem.building_model
    layers = {"ELEV": 0, "TEXT": 0, "TITLE": 0}
    entities: list[str] = []
    if not building.floor_plans or building.site is None:
        return _empty(drawing_type, units, "No floors to elevate")
    width = building.site.frontage_m or building.site.boundary.width
    for plan in building.floor_plans:
        z0 = plan.elevation_m
        z1 = plan.elevation_m + (plan.storey_height_m or 0.3)
        entities.extend(_line_entity("ELEV", 0.0, z0, width, z0))
        entities.extend(_line_entity("ELEV", 0.0, z1, width, z1))
        entities.extend(_line_entity("ELEV", 0.0, z0, 0.0, z1))
        entities.extend(_line_entity("ELEV", width, z0, width, z1))
        entities.extend(_text_entity("TEXT", width / 2.0, (z0 + z1) / 2.0, plan.name))
        layers["ELEV"] += 4
        layers["TEXT"] += 1
        for window in plan.windows:
            wx = window.center.x
            entities.extend(_line_entity("ELEV", wx - 0.4, z0 + 0.9, wx + 0.4, z0 + 0.9))
            entities.extend(_line_entity("ELEV", wx - 0.4, z0 + 2.3, wx + 0.4, z0 + 2.3))
            layers["ELEV"] += 2
    entities.extend(_title(pem, "FRONT ELEVATION (from +y looking at frontage)"))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "COMPLETE", "storey_count": len(building.floor_plans)},
    )


def _section(pem: ProjectEngineeringModel, *, drawing_type: str, units: str) -> DxfRenderResult:
    building = pem.building_model
    layers = {"SECTION": 0, "TEXT": 0, "TITLE": 0}
    entities: list[str] = []
    if not building.floor_plans or building.site is None:
        return _empty(drawing_type, units, "No floors to section")
    depth = building.site.depth_m or building.site.boundary.depth
    for plan in building.floor_plans:
        z0 = plan.elevation_m
        z1 = plan.elevation_m + (plan.storey_height_m or 0.3)
        entities.extend(_line_entity("SECTION", 0.0, z0, depth, z0))
        entities.extend(_line_entity("SECTION", 0.0, z1, depth, z1))
        layers["SECTION"] += 2
        entities.extend(_text_entity("TEXT", 0.3, (z0 + z1) / 2.0, plan.name))
        layers["TEXT"] += 1
        for space in plan.spaces:
            if space.usage is SpaceUsage.STAIR:
                y0, y1 = space.boundary.bounds[1], space.boundary.bounds[3]
                entities.extend(_line_entity("SECTION", y0, z0, y1, z1))
                layers["SECTION"] += 1
    entities.extend(_title(pem, "SECTION A-A (cut along building depth)"))
    layers["TITLE"] += 4
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "COMPLETE"},
    )


def _column_schedule(pem, *, drawing_type, units):
    return _member_schedule(pem, MemberType.COLUMN, drawing_type, units)


def _beam_schedule(pem, *, drawing_type, units):
    return _member_schedule(pem, MemberType.BEAM, drawing_type, units)


def _slab_schedule(pem, *, drawing_type, units):
    return _member_schedule(pem, MemberType.SLAB, drawing_type, units)


def _member_schedule(
    pem: ProjectEngineeringModel,
    member_type: MemberType,
    drawing_type: str,
    units: str,
) -> DxfRenderResult:
    layers = {"TEXT": 0, "TITLE": 0}
    entities: list[str] = list(_title(pem, drawing_type))
    layers["TITLE"] += 4
    y = 0.0
    headers = "ID / NAME / SECTION / LEVEL / NOTES"
    entities.extend(_text_entity("TEXT", 0.0, y, headers))
    layers["TEXT"] += 1
    y -= 0.8
    rebar = {item.member_id: item for item in pem.structural_model.reinforcement}
    sections = {
        **{item.id: item.name for item in pem.structural_model.sections.columns},
        **{item.id: item.name for item in pem.structural_model.sections.beams},
        **{item.id: item.name for item in pem.structural_model.sections.slabs},
    }
    rows = 0
    for member in pem.structural_model.members.members:
        if member.member_type is not member_type:
            continue
        bars = rebar.get(member.id)
        bar_note = ""
        if bars and bars.longitudinal:
            bar = bars.longitudinal[0]
            bar_note = f"{bar.count}∅{bar.diameter_mm:.0f}"
        elif bars and bars.slab_bottom:
            bar = bars.slab_bottom[0]
            bar_note = f"∅{bar.diameter_mm:.0f}@{bar.spacing_mm or 0:.0f}"
        line = f"{member.id}  {member.name}  {sections.get(member.section_id, '-')}  {member.level_id or '-'}  {bar_note}"
        entities.extend(_text_entity("TEXT", 0.0, y, line[:120]))
        layers["TEXT"] += 1
        y -= 0.55
        rows += 1
        if rows >= 40:
            break
    return _build_result(
        entities=entities,
        layers=layers,
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "COMPLETE" if rows else "INCOMPLETE", "row_count": rows},
    )


def _empty(drawing_type: str, units: str, reason: str) -> DxfRenderResult:
    return _build_result(
        entities=_text_entity("TEXT", 0.0, 0.0, reason),
        layers={"TEXT": 1},
        drawing_type=drawing_type,
        units=units,
        metadata={"capability_status": "INCOMPLETE", "missing_data": [reason]},
    )
