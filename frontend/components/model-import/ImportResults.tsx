export const cell: React.CSSProperties = { padding: "4px 8px", borderTop: "1px solid rgba(127,127,127,0.25)", textAlign: "start", whiteSpace: "nowrap" };
// Numbers: always an LTR run, right-aligned and tabular in both languages so columns line up in RTL tables.
export const numCell: React.CSSProperties = { ...cell, textAlign: "right", fontVariantNumeric: "tabular-nums", unicodeBidi: "isolate", direction: "ltr" };

export function Num({ v, d = 3 }: { v: number | null | undefined; d?: number }) {
  return <td style={numCell} dir="ltr">{v == null ? "—" : fmt(v, d)}</td>;
}

function Table({ head, numeric, children }: { head: React.ReactNode[]; numeric: boolean[]; children: React.ReactNode }) {
  return (
    <div style={{ overflowX: "auto", WebkitOverflowScrolling: "touch" }}>
      <table style={{ borderCollapse: "collapse", fontSize: 13, width: "100%" }}>
        <thead><tr>{head.map((h, i) => <th key={i} style={numeric[i] ? { ...numCell, fontWeight: 600 } : { ...cell, fontWeight: 600 }}>{h}</th>)}</tr></thead>
        <tbody>{children}</tbody>
      </table>
    </div>
  );
}

const h4: React.CSSProperties = { margin: "14px 0 4px", fontSize: 14 };

export function ImportResults({ a, fa, mode = "all" }: { a: ImportAnalysis; fa: boolean; mode?: "all" | "results" | "design" }) {
  const t = T[fa ? "fa" : "en"];
  const showRes = mode !== "design";
  const showDes = mode !== "results";
  const s = a.seismic;
  return (
    <div dir={fa ? "rtl" : "ltr"} style={{ border: "1px solid rgba(127,127,127,0.4)", borderRadius: 10, padding: 12, marginTop: 12 }} data-testid="model-import-results">
      <h3 style={{ margin: "0 0 4px", fontSize: 16 }}>{t.results}</h3>
      <p style={{ fontSize: 12, opacity: 0.8, margin: 0 }}>{t.engine}: <span dir="ltr">{a.engine}</span></p>

      {showRes && (
        <>
          <Table head={[t.case, "Fx", "Fy", "Fz", t.maxD]} numeric={[false, true, true, true, true]}>
            {Object.entries(a.cases).map(([k, c]) => (
              <tr key={k}>
                <td style={cell} dir="ltr">{k.replace(/^(pattern|combo|spectrum|envelope):/, "")}</td>
                <Num v={c.base_reaction_kN[0]} /><Num v={c.base_reaction_kN[1]} /><Num v={c.base_reaction_kN[2]} />
                <td style={numCell} dir="ltr">{fmt(c.max_displacement_m * 1000)} <span style={{ opacity: 0.6 }}>({c.max_displacement_node})</span></td>
              </tr>
            ))}
          </Table>

          {s && (
            <>
              <h4 style={h4}>{t.seismic} <span style={{ fontWeight: 400, fontSize: 12, opacity: 0.75 }}>({s.generated?.length ? t.generated : t.fromFile})</span></h4>
              <div style={{ display: "flex", flexWrap: "wrap", gap: 8, fontSize: 13 }} data-testid="import-seismic">
                {[[t.zone, `${s.zone} (A=${s.A})`], [t.soil, s.soil], [t.system, `${s.system} R=${s.R} Cd=${s.Cd}`], ["T", `${fmt(s.T_empirical_s)} s`],
                  ["C", fmt(s.C, 4)], [t.W, fmt(s.W_kN)], [t.V, fmt(s.V_kN)]].map(([k, v]) => (
                  <span key={String(k)} style={{ background: "rgba(127,127,127,0.15)", borderRadius: 6, padding: "2px 8px" }}>{k}: <bdi dir="ltr">{v}</bdi></span>
                ))}
              </div>
              <Table head={[t.level, t.Wi, t.Fi]} numeric={[true, true, true]}>
                {s.levels.map((l) => <tr key={l.z}><Num v={l.z} /><Num v={l.W_kN} /><Num v={l.F_kN} /></tr>)}
              </Table>
            </>
          )}

          {a.modal && a.modal.modes.length > 0 && (
            <>
              <h4 style={h4}>{t.modal}</h4>
              <Table head={[t.mode, t.T, t.mx, t.my, t.cum]} numeric={[true, true, true, true, true]}>
                {a.modal.modes.slice(0, 12).map((m) => (
                  <tr key={m.mode}><Num v={m.mode} /><Num v={m.T} d={4} /><Num v={m.mass_ratio_x * 100} d={2} /><Num v={m.mass_ratio_y * 100} d={2} />
                    <td style={numCell} dir="ltr">{fmt(m.cum_x * 100, 2)}% / {fmt(m.cum_y * 100, 2)}%</td></tr>
                ))}
              </Table>
            </>
          )}

          {a.response_spectrum && (
            <>
              <h4 style={h4}>{t.rs}</h4>
              <Table head={[t.dir, t.Vrs, t.scale]} numeric={[false, true, true]}>
                {Object.entries(a.response_spectrum.base_shear_kN).map(([d, v]) => (
                  <tr key={d}><td style={cell}>{d}</td><Num v={v} /><Num v={a.response_spectrum?.scale?.[d]} /></tr>
                ))}
              </Table>
            </>
          )}

          {a.pdelta?.applied && a.pdelta.amplification && (
            <>
              <h4 style={h4}>{t.pdelta}</h4>
              <Table head={[t.case, t.amp]} numeric={[false, true]}>
                {Object.entries(a.pdelta.amplification).map(([k, v]) => <tr key={k}><td style={cell} dir="ltr">{k}</td><Num v={v} d={4} /></tr>)}
              </Table>
            </>
          )}

          {a.drifts && a.drifts.length > 0 && (
            <>
              <h4 style={h4}>{t.drifts}</h4>
              <Table head={[t.case, t.maxDrift, t.limit, ""]} numeric={[false, true, true, false]}>
                {a.drifts.map((d) => (
                  <tr key={d.case}><td style={cell} dir="ltr">{d.case}</td><Num v={d.max} d={4} /><Num v={d.limit} d={4} />
                    <td style={{ ...cell, color: d.ok ? "#12b76a" : "#f04438" }}>{d.ok ? t.ok : t.ng}</td></tr>
                ))}
              </Table>
            </>
          )}

          <h4 style={h4}>{t.governing}</h4>
          <Table head={[t.member, "N (kN)", "V (kN)", "M (kN·m)", "T (kN·m)"]} numeric={[false, true, true, true, true]}>
            {a.governing_members.slice(0, 10).map((m) => (
              <tr key={m.member}><td style={cell} dir="ltr">{m.member}</td><Num v={m.N} /><Num v={m.V} /><Num v={m.M} /><Num v={m.T} /></tr>
            ))}
          </Table>
          {a.equilibrium && (
            <p style={{ fontSize: 12, opacity: 0.8 }}>{t.equil}: <bdi dir="ltr">{fmt(Math.max(0, ...Object.values(a.equilibrium)), 2)}</bdi>
              {a.slabs && a.slabs.count > 0 && <> · {t.slabs}: <bdi dir="ltr">{a.slabs.count}</bdi> ({t.oneWay} <bdi dir="ltr">{a.slabs.one_way}</bdi>, {t.toNodes} <bdi dir="ltr">{a.slabs.to_nodes}</bdi>)</>}</p>
          )}
        </>
      )}

      {showDes && a.design && a.design.count > 0 && (
        <>
          <h4 style={h4} data-testid="import-design">{t.design} — <bdi dir="ltr">{a.design.count}</bdi>, <span style={{ color: a.design.failing ? "#f04438" : "#12b76a" }}><bdi dir="ltr">{a.design.failing}</bdi> {t.failing}</span></h4>
          <p style={{ fontSize: 12, opacity: 0.75, margin: "0 0 4px" }} dir="ltr">{a.design.method}</p>
          <Table head={[t.member, t.section, t.ratio, t.detail]} numeric={[false, false, true, false]}>
            {a.design.members.slice(0, mode === "design" ? 100 : 15).map((d) => (
              <tr key={d.member}><td style={cell} dir="ltr">{d.member}</td><td style={cell} dir="ltr">{d.section}</td>
                <td style={{ ...numCell, color: d.ok ? undefined : "#f04438" }} dir="ltr">{fmt(d.ratio, 2)}</td>
                <td style={{ ...cell, whiteSpace: "normal", minWidth: 220 }} dir="ltr">{d.detail}</td></tr>
            ))}
          </Table>
        </>
      )}

      {a.assumptions && a.assumptions.length > 0 && (
        <details style={{ marginTop: 10 }}><summary style={{ fontSize: 13, cursor: "pointer" }}>{t.assumptions} ({a.assumptions.length})</summary>
          <ul style={{ fontSize: 12 }}>{a.assumptions.map((x) => <li key={x.en}>{fa ? x.fa : x.en}</li>)}</ul></details>
      )}
      <details style={{ marginTop: 6 }}><summary style={{ fontSize: 13, cursor: "pointer" }}>{t.notes} ({a.notes.length})</summary>
        <ul style={{ fontSize: 12, opacity: 0.8 }} dir="ltr">{a.notes.map((n) => <li key={n}>{n}</li>)}</ul></details>
    </div>
  );
}
